def run_episodes(policy_spec: str, backend_kind: str, seeds: Iterable[int], *,
                 trace: str | Path = DEFAULT_TRACE, horizon: int = DEFAULT_HORIZON,
                 omega=None, out: str | None = None, backend_kwargs: dict | None = None,
                 log_obs: bool = True, belief_mode: str = "sim-fifo") -> list[dict]:
    import backends as B

    factory = trace_env_factory(trace, horizon)
    template = factory()
    policy = make_policy(policy_spec, template)
    cond = (np.full(3, 1.0 / 3.0, dtype=np.float32) if omega is None
            else np.asarray(omega, dtype=np.float32))
    sink = open(out, "a", encoding="utf-8") if out else None
    summaries = []
    try:
        for seed in seeds:
            name = f"e{seed}-{_slug(policy_spec)}"
            schedule = ArrivalSchedule(factory, seed, horizon, prefix=name)
            tmpl = factory()
            if schedule.offset is not None and tmpl.trace is not None:
                tmpl.trace.offset = schedule.offset
            be = B.make_backend(backend_kind, template=tmpl, run_id=name,
                                **(backend_kwargs or {}))
            meta = {"policy_spec": policy_spec, "run_id": name,
                    "p3_code_sha256": p3_code_fingerprint(),
                    "calibrated": getattr(be, "calibrated", None)}
            try:
                ctl = ReplayController(be, policy, schedule, cond=cond,
                                       template_env=tmpl, horizon=horizon, sink=sink,
                                       log_obs=log_obs, belief_mode=belief_mode, meta=meta)
                res = ctl.run()
            finally:
                be.close()
            summaries.append(res.summary)
    finally:
        if sink:
            sink.close()
    return summaries


def action_seed(base: int, policy_index: int, window_index: int) -> int:
    """Registered action-sampling seed for SAMPLED learned arms (protocol v1 10):
    base + 1000*policy + window. Shared by both live repetitions and by sim."""
    return int(base) + 1000 * int(policy_index) + int(window_index)


def run_specs(policy_spec: str, backend_kind: str, specs, *, omega=None,
              out: str | None = None, backend_kwargs: dict | None = None,
              log_obs: bool = True, belief_mode: str = "sim-fifo",
              step_seconds: float = 1.0, deadline_eps_s: float = 0.0,
              run_id: str | None = None, torch_seed: int | None = None,
              extra_meta: dict | None = None, energy_probe=None,
              collect_timeout_s: float = 30.0) -> list[dict]:
    """Run frozen episodes (controller/episodes.py EpisodeSpec) -- the protocol-v1
    entry point. Fixed windows replay through P3's `forced_offset`; every summary
    carries the episode tuple, the workload digests and the cohort endpoint.

    `torch_seed`: seeds torch AFTER the policy is loaded and BEFORE the episode
    (sampled learned arms only; greedy arms draw no random numbers)."""
    import backends as B
    import episodes as E

    E.check_traces()
    cond = (np.full(3, 1.0 / 3.0, dtype=np.float32) if omega is None
            else np.asarray(omega, dtype=np.float32))
    sink = open(out, "a", encoding="utf-8") if out else None
    summaries = []
    policy_cache = None
    try:
        for spec in specs:
            factory = E.env_factory(spec)
            template = factory()
            head = policy_spec.partition(":")[0]
            if head in ("learned", "p3pt"):
                policy_cache = policy_cache or make_policy(policy_spec, template)
                policy = policy_cache
            else:
                policy = make_policy(policy_spec, template)
            name = run_id or f"{spec.name}-{_slug(policy_spec)}"
            schedule = ArrivalSchedule(factory, spec.routing_seed, spec.horizon, prefix=name)
            tmpl = factory()
            kw = dict(backend_kwargs or {})
            if backend_kind == "live":
                kw.setdefault("step_seconds", step_seconds)
            be = B.make_backend(backend_kind, template=tmpl, run_id=name, **kw)
            greedy = getattr(policy, "greedy", None)
            if torch_seed is not None and greedy is False:
                import torch
                torch.manual_seed(int(torch_seed))
            meta = {"policy_spec": policy_spec, "run_id": name, "episode": spec.as_dict(),
                    "p3_tree": str(P3_CODE), "p3_code_sha256": p3_code_fingerprint(),
                    "calibrated": getattr(be, "calibrated", None),
                    "action_rule": (None if greedy is None else ("greedy" if greedy else "sampled")),
                    "torch_seed": torch_seed if greedy is False else None,
                    "policy_meta": getattr(policy, "blob", {}).get("meta") if hasattr(policy, "blob") else None,
                    **(extra_meta or {})}
            try:
                ctl = ReplayController(be, policy, schedule, cond=cond, template_env=tmpl,
                                       horizon=spec.horizon, sink=sink, log_obs=log_obs,
                                       belief_mode=belief_mode, meta=meta,
                                       step_seconds=step_seconds,
                                       deadline_eps_s=deadline_eps_s,
                                       energy_probe=energy_probe,
                                       collect_timeout_s=collect_timeout_s)
                res = ctl.run()
            finally:
                be.close()
            summaries.append(res.summary)
    finally:
        if sink:
            sink.close()
    return summaries


def resolve_episodes(arg: str):
    """'primary' | 'pilot' | 'legacy' | comma-separated episode names."""
    import episodes as E
    sets = {"primary": E.PRIMARY, "pilot": E.PILOT, "legacy": E.LEGACY}
    if arg in sets:
        return list(sets[arg])
    return [E.get(n) for n in arg.split(",") if n]


def _slug(s: str) -> str:
    keep = "".join(c if c.isalnum() else "-" for c in s.lower())
    while "--" in keep:
        keep = keep.replace("--", "-")
    return keep.strip("-")[:30]


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description="P4 replay controller (tick loop).")
    p.add_argument("--backend", choices=("sim", "kube-model", "live"), default="sim",
                   help="sim = the P3 simulator as cluster (bit-exact); kube-model = "
                        "a MODEL of Kubernetes semantics; live = real cluster")
    p.add_argument("--policy", default="heur_local:1.0",
                   help="default | heur_local:TAU | heur_local_urgent:TAU | "
                        "heur_leastloaded:TAU | heur_dpp:V | learned:PATH[:greedy]")
    p.add_argument("--seeds", default=",".join(map(str, DEFAULT_SEEDS)),
                   help="legacy path: training trace, offset drawn from the seed")
    p.add_argument("--episodes", default=None,
                   help="protocol v1: primary | pilot | legacy | names (e.g. h40000,p49000)")
    p.add_argument("--deadline-eps", type=float, default=0.0,
                   help="live outcome rule tolerance, seconds (FREEZE2 timestamp resolution)")
    p.add_argument("--torch-seed", type=int, default=None,
                   help="action seed for SAMPLED learned arms (protocol v1 10)")
    p.add_argument("--run-id", default=None)
    p.add_argument("--image", default=None, help="live: workload image, pinned by digest")
    p.add_argument("--pull-policy", default=None, help="live: imagePullPolicy (campaign: Never)")
    p.add_argument("--horizon", type=int, default=DEFAULT_HORIZON)
    p.add_argument("--trace", default=str(DEFAULT_TRACE))
    p.add_argument("--omega", default=None, help="preference for conditioned actors, e.g. 0.33,0.33,0.34")
    p.add_argument("--out", default=None, help="append JSONL (header, ticks, summary)")
    p.add_argument("--no-obs", action="store_true", help="do not log the observation matrix")
    p.add_argument("--belief", choices=("sim-fifo", "prescribed"), default="sim-fifo")
    # live-only
    p.add_argument("--context", default="k3d-pltr-p4")
    p.add_argument("--namespace", default="pltr-p4")
    p.add_argument("--step-seconds", type=float, default=1.0)
    p.add_argument("--iters-per-work-unit", type=int, default=None,
                   help="calibration constant (trace_to_pods --help-calibration); "
                        "without it every manifest is stamped UNCALIBRATED")
    p.add_argument("--allow-uncalibrated", action="store_true")
    # kube-model only
    p.add_argument("--host-cores", type=float, default=12.0)
    return p


def main(argv=None) -> int:
    ns = build_parser().parse_args(argv)
    seeds = [int(s) for s in ns.seeds.split(",") if s]
    omega = None if ns.omega is None else [float(x) for x in ns.omega.split(",")]
    kw: dict = {}
    if ns.backend == "live":
        if ns.iters_per_work_unit is None and not ns.allow_uncalibrated:
            print("refusing a live run without --iters-per-work-unit (calibration). "
                  "Pass --allow-uncalibrated for a smoke test whose numbers must not be "
                  "reported.", file=sys.stderr)
            return 2
        kw = {"context": ns.context, "namespace": ns.namespace,
              "step_seconds": ns.step_seconds,
              "iters_per_work_unit": ns.iters_per_work_unit,
              "image": ns.image, "image_pull_policy": ns.pull_policy}
    elif ns.backend == "kube-model":
        kw = {"host_cores": ns.host_cores}
    if ns.episodes:
        sums = run_specs(ns.policy, ns.backend, resolve_episodes(ns.episodes), omega=omega,
                         out=ns.out, backend_kwargs=kw, log_obs=not ns.no_obs,
                         belief_mode=ns.belief, step_seconds=ns.step_seconds,
                         deadline_eps_s=ns.deadline_eps, run_id=ns.run_id,
                         torch_seed=ns.torch_seed)
    else:
        sums = run_episodes(ns.policy, ns.backend, seeds, trace=ns.trace, horizon=ns.horizon,
                            omega=omega, out=ns.out, backend_kwargs=kw,
                            log_obs=not ns.no_obs, belief_mode=ns.belief)
    for s in sums:
        print(json.dumps({k: s[k] for k in (
            "backend", "policy", "seed", "return_vec", "completed_tasks",
            "sla_violations", "refused_bindings", "migrations", "cpu_seconds",
            "cpu_seconds_source", "cohort_size", "cohort_not_met_rate",
            "workload_identity_ok", "conservation_ok")}, default=_json_default))
    return 0


