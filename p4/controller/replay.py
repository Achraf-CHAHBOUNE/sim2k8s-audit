# 4. Shadow env — for heuristics that read simulator internals
# --------------------------------------------------------------------------- #
def build_shadow_env(template, snap: ClusterSnapshot, rng, cost_sum: np.ndarray,
                     ledger: Ledger, ep_counts: dict) -> Any:
    """A CloudAllocationEnv whose state mirrors the cluster snapshot.

    LeastLoadedPolicy reads env.servers; DriftPlusPenaltyPolicy additionally
    clones the env and steps it, i.e. it plans with the SIMULATOR as its model
    of the cluster — including the one-head-per-server service rule that
    Kubernetes does not have (MAPPING.md G-6). Inputs that cannot be read from
    a cluster are filled from named sources:
      * server speed: cloud_env's fleet spec (G-3: no Kubernetes counterpart);
      * remaining work of a RUNNING pod: the snapshot's value if the backend
        knows it (simulator), else the ledger's belief, advanced by the
        simulator's own FIFO rule (O-7: not observable);
      * env.rng: the schedule's copy, so the clone spawns the true next arrivals.
    """
    from cloud_env import Server, Task

    env = copy.copy(template)
    env.t = snap.step
    sc = snap.scale
    servers = []
    for nd in sorted(snap.nodes, key=lambda x: x.index):
        def task_of(p: PodState, running: bool) -> Task:
            rem = p.remaining_work_units
            if rem is None:
                rem = (ledger.recs[p.name].belief_remaining if running else p.work_units)
            return Task(cpu=sc.cpu_to_sim(p.cpu_request_millis),
                        mem=sc.mem_to_sim(p.mem_request_bytes),
                        work=p.work_units, remaining=rem,
                        arrival_t=p.arrival_step, deadline_t=p.deadline_step)
        servers.append(Server(
            cpu_cap=nd.sim_cpu_cap(sc), mem_cap=nd.sim_mem_cap(sc),
            speed=float(template._fleet_spec[nd.index][2]),
            queue_cap=snap.queue_cap,
            running=[task_of(p, True) for p in snap.bound_pods(nd.index)],
            arrivals=[task_of(p, False) for p in snap.arrival_pods(nd.index)]))
    env.servers = servers
    env.rng = rng
    env._ep_metrics = {"completed": ep_counts.get("completed", 0),
                       "latency_sum": ep_counts.get("latency_sum", 0.0),
                       "energy_sum": ep_counts.get("energy_sum", 0.0),
                       "sla_violations": ep_counts.get("sla_violations", 0),
                       "queue_trace": [], "cost_sum": cost_sum.copy()}
    return env


def advance_belief(ledger: Ledger, snap: ClusterSnapshot, speeds, exclude: set) -> None:
    """Advance the remaining-work belief by cloud_env._process (cloud_env.py:302-320):
    per node, the FIFO head is served at `speed`, leftover budget is lost."""
    for nd in sorted(snap.nodes, key=lambda x: x.index):
        budget = float(speeds[nd.index])
        for p in snap.bound_pods(nd.index):
            if p.name in exclude:
                continue
            r = ledger.recs[p.name]
            if budget <= 1e-9:
                break
            w = min(r.belief_remaining, budget)
            r.belief_remaining -= w
            budget -= w
            if r.belief_remaining > 1e-9:
                break


