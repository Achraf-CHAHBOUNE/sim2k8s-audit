#!/usr/bin/env python3
"""replay.py — the P4 replay controller: one tick loop, any policy, any backend.

Each tick reproduces one ``CloudAllocationEnv.step`` (p3/code/cloud_env.py:185-246)
against a cluster that is either simulated or real:

    observe(t)      backend snapshot + controller ledger -> bridge/observation.py
    decide          policy.act(obs, cond)   (learned, heuristic, or the no-op
                                             default-scheduler policy)
    t <- t + 1
    act             bridge/action.plan_step -> backend executor   (cloud_env 193-209)
    expire          bridge/action.plan_expiry on a fresh snapshot (cloud_env 211-212)
    advance         sim: FIFO service; model: processor sharing; live: wall clock
    measure         reward vector, costs c1..c3, completions, refusals, CPU-seconds
    admit           the trace arrivals of step t                  (cloud_env 241)

The loop is the same for every backend. What differs is who moves the work:

  * ``SimulatorBackend``  — the P3 simulator itself is the "cluster". With it the
    controller must reproduce ``env.step`` bit for bit, which is what
    test_replay.py checks for every policy type. This is the proof that the
    controller + bridges add no behaviour of their own.
  * ``KubeModelBackend``  — a MODEL of Kubernetes semantics (concurrent service,
    kubelet admission, refusals). Exercises every code path the live run needs.
    Its numbers are a model, never a result.
  * ``LiveBackend``       — the real cluster through the `kubernetes` client.
    Behind ``--backend live`` and a kube-context check; never imported unless
    asked for, so everything else runs without the client installed.

What the controller has to carry that Kubernetes does not hold (MAPPING.md):
the per-agent arrival buffers and their FIFO order (O-9), the routing of each
pending pod after MIGRATE (A-3), the bind order that defines the simulator's
service head (G-6), the expiry rule (G-7), the cumulative constraint costs a
drift-plus-penalty controller reads, and — for policies that read simulator
internals — a belief about the remaining work of running pods (O-7).

Usage (dry run, no cluster):
    python p4/controller/replay.py --backend sim --policy heur_local:1.0
    python p4/controller/replay.py --backend kube-model --policy default --out run.jsonl
Live (only after p4/cluster/up.sh --create; see p4/README.md):
    python p4/controller/replay.py --backend live --policy learned:w.pt --out live.jsonl
"""
