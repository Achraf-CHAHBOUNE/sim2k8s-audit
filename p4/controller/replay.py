class Policy(Protocol):
    def act(self, obs, cond=None): ...


class DefaultSchedulerPolicy:
    """The kube-scheduler baseline as a policy: decides nothing.

    `native_scheduler = True` tells the controller to create pods with
    schedulerName=default-scheduler and to issue no binding of its own. On the
    live cluster kube-scheduler then binds them; on the dry-run backends a
    documented EMULATION of its default scoring does (backends.emulate_kube_scheduler).
    The expiry rule is applied identically (MAPPING.md G-7)."""

    name = "default-scheduler"
    native_scheduler = True
    info_class = "native-kube-scheduler"

    def act(self, obs, cond=None):
        return np.full(np.asarray(obs).shape[0], DEFER, dtype=int), None


class RateLimitedSchedulerPolicy(DefaultSchedulerPolicy):
    """Arm A1 (protocol v1 3.2): the UNMODIFIED kube-scheduler plus one control
    on eligibility. Every pod is created with the scheduling gate
    `pltr-ma.io/rate`; at each tick the controller removes gates so that at most
    `release_cap` pods are released-but-unbound at any time, in original-arrival
    order, with no carry-over. Filtering, scoring and binding stay native.
    `release_cap=None` releases every gate at once: the uncapped parity
    condition, which must behave like A0 before A1 is admitted."""

    gated = True
    info_class = "native-kube-scheduler+release-gate"

    def __init__(self, release_cap: int | None = 3):
        self.release_cap = None if release_cap is None else int(release_cap)
        self.name = ("rate-limited-kube-scheduler" if release_cap is not None
                     else "rate-limited-kube-scheduler:uncapped")


#: What each policy reads. Recorded in every log so the information asymmetry
