@dataclass(frozen=True)
class ScheduledTask:
    name: str
    step: int
    agent: int                 # cloud_env.py:261 routing (SYNTHESIZED, MAPPING O-9)
    cpu: float
    mem: float
    work: float
    deadline_step: int
    index: int                 # global index in the episode (manifest numbering)
    #: position in cloud_env's GENERATION order (the order `_spawn_arrivals_impl`
    #: creates tasks and P3's workload fingerprint hashes them). `index` follows the
    #: harvest order (by server, then buffer), which is NOT generation order when
    #: a step has several arrivals. -1 = unknown (archived tree).
    ordinal: int = -1

    @property
    def slack(self) -> int:
        return self.deadline_step - self.step


class ArrivalSchedule:
    """Every arrival of one episode, with the simulator's own routing.

    Built by running ``CloudAllocationEnv._spawn_arrivals`` itself (with the
    buffers cleared between steps), so offset draw, trace window, per-task
    routing draws and their order are those of ``env.reset(seed)`` + ``env.step``
    by construction. In trace mode arrivals do not depend on actions, so the
    schedule is fixed before the episode starts. The RNG state after each step's
    spawn is kept: a drift-plus-penalty controller clones the env and needs it
    (heuristics.clone_env deep-copies env.rng).
    """

    def __init__(self, env_factory: Callable[[], Any], seed: int, horizon: int,
                 prefix: str = "task"):
        env = env_factory()
        # Generation order and P3's exogenous-workload fingerprint come from the
        # simulator itself: its recorder is armed (no RNG draw, no state change —
        # p3/revision_v2/src/cloud_env.py `_wl_add`) and each `_wl_add` call is
        # observed in order. Tasks are kept alive so that id() is never reused.
        ordinal: dict[int, int] = {}
        keep: list = []
        self.p3_digest = None
        if hasattr(env, "_wl_add"):
            env.cost_log, env.wl_log = [], []
            original = env._wl_add

            def observe(task, server, _orig=original):
                ordinal[id(task)] = len(keep)
                keep.append(task)
                _orig(task, server)
            env._wl_add = observe
        env.reset(seed=seed)
        self.seed = int(seed)
        self.horizon = int(horizon)
        self.n_agents = env.N
        self.offset = getattr(env.trace, "offset", None) if env.trace is not None else None
        self.by_step: dict[int, list[ScheduledTask]] = {}
        self._rng_after: dict[int, Any] = {}
        idx = 0

        def harvest(t: int) -> None:
            nonlocal idx
            out = []
            for i, srv in enumerate(env.servers):
                for task in srv.arrivals:
                    out.append(ScheduledTask(
                        name=f"{prefix}-{idx:06d}", step=t, agent=i,
                        cpu=task.cpu, mem=task.mem, work=task.work,
                        deadline_step=task.deadline_t, index=idx,
                        ordinal=ordinal.get(id(task), -1)))
                    idx += 1
            self.by_step[t] = out
            self._rng_after[t] = copy.deepcopy(env.rng)

        harvest(0)
        for t in range(1, self.horizon + 1):
            for srv in env.servers:
                srv.arrivals = []
                srv.running = []
            env.t = t
            env._spawn_arrivals()
            harvest(t)
        if getattr(env, "_wl", None) is not None:
            self.p3_digest = env._wl.hexdigest()
            mine = workload_digest(self.tasks())
            if mine != self.p3_digest:      # the generation order is not what we think
                raise RuntimeError(f"seed {seed}: recomputed workload digest {mine} != "
                                   f"cloud_env's {self.p3_digest}")

    def tasks(self) -> list[ScheduledTask]:
        return [t for v in self.by_step.values() for t in v]

    def at(self, t: int) -> list[ScheduledTask]:
        return self.by_step.get(t, [])

    def rng_after(self, t: int):
        """Copy of env.rng as it stands right after the spawn at step t."""
        return copy.deepcopy(self._rng_after[t])

    @property
    def n_tasks(self) -> int:
        return sum(len(v) for v in self.by_step.values())


def workload_digest(tasks: Iterable[ScheduledTask]) -> str:
    """P3's exogenous-workload fingerprint over ORIGINAL arrivals only, in
    generation order, with P3's byte layout (p3/revision_v2/src/cloud_env.py
    `_wl_add`): arrival step, initial server, cpu, mem, work, deadline. Requeued
    pods, migrations, names and admission outcomes are never part of it."""
    import struct
    tasks = list(tasks)
    if any(t.ordinal < 0 for t in tasks):
        raise ValueError("workload_digest needs source ordinals (corrected P3 tree)")
    h = hashlib.sha256()
    for t in sorted(tasks, key=lambda x: x.ordinal):
        h.update(struct.pack("<iiddd", t.step, t.agent, t.cpu, t.mem, t.work))
        h.update(struct.pack("<i", t.deadline_step))
    return h.hexdigest()


