@dataclass
class EpisodeResult:
    summary: dict
    ticks: list[dict] = field(default_factory=list)


class ReplayController:
    def __init__(self, backend, policy, schedule: ArrivalSchedule, *,
                 cond=None, template_env=None, horizon: int | None = None,
                 sink=None, log_obs: bool = True, belief_mode: str = "sim-fifo",
                 sla_penalty: float = SLA_PENALTY, meta: dict | None = None,
                 step_seconds: float = 1.0, deadline_eps_s: float = 0.0,
                 energy_probe=None, collect_timeout_s: float = 30.0):
        self.backend = backend
        #: live: pods deleted at expiry whose final status is still awaited
        self.draining: dict[str, PodRecord] = {}
        self.collect_timeout_s = float(collect_timeout_s)
        #: infrastructure conditions seen during the episode (protocol v1 6.4)
        self.infra_events: list[dict] = []
        #: A1 audit: observed gate state disagreeing with the issued operations
        self.gate_mismatches: list[dict] = []
        #: host energy proxy (energy/host_energy.py), read at tick 0 and after the
        #: last tick, so start-up and teardown are outside the interval (v1 7.4)
        self.energy_probe = energy_probe
        self.policy = policy
        self.schedule = schedule
        self.cond = None if cond is None else np.asarray(cond, dtype=np.float32)
        self.template_env = template_env
        self.horizon = schedule.horizon if horizon is None else int(horizon)
        self.sink = sink
        self.log_obs = log_obs
        if belief_mode not in ("sim-fifo", "prescribed"):
            raise ValueError(belief_mode)
        self.belief_mode = belief_mode
        self.sla_penalty = float(sla_penalty)
        self.meta = meta or {}
        self.native = bool(getattr(policy, "native_scheduler", False))
        self.gated = bool(getattr(policy, "gated", False))
        self.release_cap = getattr(policy, "release_cap", None)
        self.step_seconds = float(step_seconds)
        self.deadline_eps_s = float(deadline_eps_s)
        self.admitted_originals: list[ScheduledTask] = []
        self.gate_violations = 0
        self.reads_env = policy_reads_env(policy)
        if self.reads_env and template_env is None:
            raise ValueError("this policy reads simulator internals; pass template_env")
        self.ledger = Ledger()

    # -- helpers ------------------------------------------------------------ #
    def _emit(self, rec: dict) -> None:
        if self.sink is not None:
            self.sink.write(json.dumps(rec, default=_json_default) + "\n")

    def _observe(self, step: int) -> ClusterSnapshot:
        snap = self.ledger.overlay(self.backend.snapshot(step))
        for p in snap.pods:                      # live audit fields, first sight
            r = self.ledger.recs.get(p.name)
            if r is not None:
                r.uid = r.uid or p.uid
                r.scheduled_at = r.scheduled_at or p.scheduled_at
        return snap

    def _infra_check(self, snap: ClusterSnapshot, t: int) -> list[dict]:
        """Node NotReady or a workload container that cannot start (image missing,
        pull back-off, create error): infrastructure failures (protocol v1 6.4),
        never a high not-met rate."""
        from backends import INFRA_WAITING_REASONS
        ev = [{"t": t, "kind": "node-not-ready", "node": nd.name}
              for nd in snap.nodes if nd.ready is False]
        ev += [{"t": t, "kind": "container-waiting", "pod": p.name, "reason": p.waiting_reason}
               for p in snap.pods if p.waiting_reason in INFRA_WAITING_REASONS]
        self.infra_events.extend(ev)
        return ev

    def _collect(self, final: bool) -> int:
        """Final status of pods deleted at expiry (live). Each
        tick: one pass. At the end: bounded polling, then `lost`."""
        if not self.draining or not getattr(self.backend, "retains_evidence", False):
            return 0
        dl = self.collect_timeout_s if final else 0.0
        got = self.backend.collect(list(self.draining), deadline_s=dl)
        for name, ev in got.items():
            r = self.draining.pop(name)
            r.evidence = {**(r.evidence or {}), "first_read": r.evidence, **ev}
        if final:
            for name, r in list(self.draining.items()):
                r.evidence = {**(r.evidence or {}), "first_read": r.evidence, "final": False,
                              "lost": f"no final status within {self.collect_timeout_s}s"}
                self.backend.gc([name])          # cleanup; the evidence stays lost
                self.draining.pop(name)
        return len(got)

    def _admit(self, tasks: list[ScheduledTask], step: int) -> None:
        for task in tasks:
            rec = self.ledger.admit(task)
            rec.released = not self.gated
            self.admitted_originals.append(task)
        # Called on EVERY step, even with no arrivals: the simulator backend
        # must run cloud_env._spawn_arrivals at each step to stay in RNG sync.
        self.backend.admit(tasks, step, self.native,
                           [t.name for t in tasks], [t.agent for t in tasks],
                           gated=self.gated)

    def _admit_lags(self, tasks) -> list[float]:
        at = getattr(self.backend, "admit_times", None) or {}
        out = []
        for task in tasks:
            planned, actual = at.get(task.name, (None, None))
            if planned is not None and actual is not None:
                out.append(actual - planned)
        return out

    def _manifest_digest(self) -> str | None:
        """Episode manifest digest (protocol v1 5.3): per-pod digests of the
        ORIGINAL arrivals in source-ordinal order; equal across arms by rule."""
        man = getattr(self.backend, "manifests", None)
        if not man:
            return None
        h = hashlib.sha256()
        for task in sorted(self.admitted_originals, key=lambda x: (x.ordinal, x.index)):
            d = man.get(task.name)
            if d is None:
                return None
            h.update(d.encode())
        return h.hexdigest()

    def _order_key(self, name: str):
        r = self.ledger.recs[name]
        o = r.task.ordinal if r.task.ordinal >= 0 else r.task.index
        return (o, r.enqueue_seq, name)

    def _plan_releases(self, snap: ClusterSnapshot) -> tuple[list[Op], dict]:
        """Arm A1 release rule (protocol v1 3.2). O = released-but-unbound pods
        in this snapshot; release max(0, cap - O) gated pods in original-arrival
        order; no carry-over. The invariant O <= cap is checked on every
        snapshot; a violation is counted and voids the episode downstream."""
        pend = [p for p in snap.pods if p.node_index is None and not p.is_terminal
                and p.name in self.ledger.recs]
        observed = getattr(self.backend, "kind", "") == "live"
        if observed:
            # Audit: the OBSERVED gate state against the issued
            # operations. A pod we released that still shows its gate, or a gate
            # that vanished without our patch, is recorded; the ledger adopts the
            # observation for an unexpected release, so the cap counts it.
            for p in pend:
                r = self.ledger.recs[p.name]
                if r.released and p.gated:
                    self.gate_mismatches.append({"t": snap.step, "pod": p.name,
                                                 "kind": "released-but-still-gated"})
                elif not r.released and not p.gated:
                    self.gate_mismatches.append({"t": snap.step, "pod": p.name,
                                                 "kind": "ungated-without-release"})
                    r.released = True
            o_now = sum(1 for p in pend if not p.gated or self.ledger.recs[p.name].released)
        else:
            o_now = sum(1 for p in pend if self.ledger.recs[p.name].released)
        cap = self.release_cap
        if cap is not None and o_now > cap:
            self.gate_violations += 1
        waiting = sorted((p.name for p in pend if not self.ledger.recs[p.name].released),
                         key=self._order_key)
        k = len(waiting) if cap is None else max(0, cap - o_now)
        ops = [Op(kind="release-gate", agent=-1, pod=n, calls_api=True,
                  reason=f"A1 release: O={o_now}, cap={cap}") for n in waiting[:k]]
        return ops, {"released_unbound_before": o_now, "released_now": len(ops),
                     "gated_waiting_after": len(waiting) - len(ops), "cap": cap}

    def _speeds(self):
        if self.template_env is not None:
            return [float(s[2]) for s in self.template_env._fleet_spec]
        return list(np.linspace(1.0, 1.5, self.schedule.n_agents))   # cloud_env.py:126

    # -- one episode -------------------------------------------------------- #
    def run(self) -> EpisodeResult:
        be, led = self.backend, self.ledger
        be.reset(self.schedule, self.native)
        cpu0, cpu_src = be.cpu_seconds()
        self._emit({"type": "header", "backend": be.kind,
                    "policy": getattr(self.policy, "name", type(self.policy).__name__),
                    "info_class": policy_info_class(self.policy),
                    "native_scheduler": self.native, "seed": self.schedule.seed,
                    "trace_offset": self.schedule.offset, "horizon": self.horizon,
                    "n_tasks_scheduled": self.schedule.n_tasks,
                    "cond": None if self.cond is None else self.cond.tolist(),
                    "belief_mode": self.belief_mode, **self.meta})

        t = 0
        # Energy interval = tick 0 .. end of tick H (protocol v1 7.4): read BEFORE
        # the first admission, so a native scheduler binding tick-0 pods is
        # inside the interval for every arm.
        e0 = self.energy_probe.read() if self.energy_probe is not None else None
        te0 = time.monotonic()
        self._admit(self.schedule.at(0), 0)
        ret = np.zeros(3)
        cost_sum = np.zeros(3)
        ep = {"completed": 0, "latency_sum": 0.0, "energy_sum": 0.0, "sla_violations": 0}
        tot = {"migrations": 0, "idle_decisions": 0, "refused_sync": 0,
               "refused_kubelet": 0, "requeues": 0, "failed_other": 0,
               "expired_bound": 0, "expired_pending": 0, "binds": 0}
        queue_trace, ticks = [], []
        max_age, stale_ticks = 0.0, 0
        clamp_ticks = 0
        completion_s: list[float] = []

        be_clock = getattr(be, "clock", None)
        live_clock = be_clock is not None and getattr(be, "t0", None) is not None

        def rel():          # seconds since t0 on the backend clock (live only)
            return (be_clock() - be.t0) if live_clock else None
        lags: list[float] = []
        timing = {"lag_s": [], "lag_decision_s": [], "admit_lag_s": [], "overrun_s": []}
        admit_lags_tick0 = self._admit_lags(self.schedule.at(0))
        timing["admit_lag_s"].extend(admit_lags_tick0)
        gate_log: dict | None = None
        for k in range(1, self.horizon + 1):
            tick_t0 = time.monotonic()
            planned = (k - 1) * self.step_seconds
            t_obs = rel()
            # ---- observe + decide (state at time t) ----------------------- #
            snap = self._observe(t)
            infra_now = self._infra_check(snap, t) if be.kind == "live" else []
            obs, report = build_observation(snap)
            if snap.max_info_age_s is not None:
                max_age = max(max_age, snap.max_info_age_s)
            stale_ticks += report.staleness_warning is not None
            clamp_ticks += bool(report.clamped)
            if self.reads_env:
                self.policy.env = build_shadow_env(
                    self.template_env, snap, self.schedule.rng_after(t),
                    cost_sum, led, ep)
            actions, _ = self.policy.act(obs, self.cond)
            actions = np.asarray(actions, dtype=int).reshape(-1)
            t_dec = rel()

            # ---- act (time t+1) ------------------------------------------- #
            t = k
            snap.step = t
            if self.native:
                plan_ops, migrate_count, idle = [], 0, ()
                if self.gated:
                    rel_ops, gate_log = self._plan_releases(snap)
                    for op in be.apply(rel_ops):
                        if op.applied and not op.refused:
                            led.recs[op.pod].released = True
                    gate_log["release_ops"] = [o.pod for o in rel_ops]
                    gate_log["release_done_s"] = rel()
                if be.emulates_scheduler:
                    from backends import emulate_kube_scheduler
                    eligible = (None if not self.gated else
                                {n for n, r in led.recs.items() if r.released})
                    plan_ops = emulate_kube_scheduler(snap, eligible=eligible)
            else:
                plan = plan_step(snap, actions)
                plan_ops, migrate_count, idle = plan.ops, plan.migrate_count, plan.idle_agents
            applied = be.apply(plan_ops)
            for op in applied:
                if op.kind == "bind":
                    if op.refused:
                        tot["refused_sync"] += 1
                    else:
                        led.on_bind(op.pod, _node_index(snap, op.target_node), t)
                        tot["binds"] += 1
                elif op.kind == "retarget" and not op.refused:
                    led.on_retarget(op.pod, op.target_agent)
            tot["migrations"] += migrate_count
            tot["idle_decisions"] += len(idle)

            # ---- expire (cloud_env._expire_overdue, on the post-action state) #
            post = self._observe(t)
            exp_ops = plan_expiry(post)
            be.apply(exp_ops)
            expired = set()
            for op in exp_ops:
                # The simulator counts the expiry the moment its rule fires; we do
                # the same whether or not the delete call succeeded (a refused
                # delete is a pod that had just finished — logged on the op).
                r = led.recs[op.pod]
                tot["expired_bound" if r.state == "bound" else "expired_pending"] += 1
                r.state = "expired"
                r.evidence = op.evidence
                expired.add(op.pod)
            sla_step = len(exp_ops)
            if getattr(be, "retains_evidence", False):
                for op in exp_ops:
                    self.draining[op.pod] = led.recs[op.pod]
            # Lag of the ACTION (binding / release / expiry calls issued) behind
            # the planned start of step k; decision lag kept too.
            t_ops = rel()
            lag = None if t_ops is None else t_ops - planned
            if lag is not None:
                lags.append(lag)
                timing["lag_s"].append(lag)
                timing["lag_decision_s"].append(t_dec - planned)
            if gate_log is not None and self.gated and be.kind == "live":
                # post-release state as the cluster reports it
                pend_post = [p for p in post.pods if p.node_index is None and not p.is_terminal]
                gate_log["released_unbound_after"] = sum(1 for p in pend_post if not p.gated)
                if (self.release_cap is not None
                        and gate_log["released_unbound_after"] > self.release_cap):
                    self.gate_violations += 1

            # ---- advance (service happens here) --------------------------- #
            if self.belief_mode == "sim-fifo":
                advance_belief(led, post, self._speeds(), expired)
            adv = be.advance(t)
            if be.kind == "live":
                timing["overrun_s"].append(adv.get("tick_overrun_s"))
            if self.energy_probe is not None:
                self.energy_probe.read()        # every tick: wrap-safe

            # ---- measure -------------------------------------------------- #
            m = self._observe(t)
            if be.kind == "live":
                infra_now = infra_now + self._infra_check(m, t)
            completed_now, refused_now = self._reconcile(m, t, completion_s, tot)
            self._collect(final=False)
            if refused_now:
                self._requeue(refused_now, t, tot)
                m = self._observe(t)
            for name, lat in completed_now:
                ep["completed"] += 1
                ep["latency_sum"] += lat
            energy = 0.0
            backlog_total = 0
            in_system = 0
            for nd in sorted(m.nodes, key=lambda x: x.index):
                run = m.bound_pods(nd.index)
                util = sum(m.scale.cpu_to_sim(p.cpu_request_millis) for p in run) / nd.sim_cpu_cap(m.scale)
                energy += SIM_P_IDLE + SIM_P_DYN * min(util, UTIL_CLAMP)
                backlog_total += len(run)
                in_system += len(run) + len(m.arrival_pods(nd.index))
            energy += MIGRATE_ENERGY * migrate_count
            reward = np.array([-in_system, -energy, -self.sla_penalty * float(sla_step)],
                              dtype=np.float32)
            cost = constraint_costs(m, sla_step)
            ret += reward
            cost_sum += cost
            ep["energy_sum"] += energy
            ep["sla_violations"] += sla_step
            queue_trace.append(backlog_total)

            tick = {"type": "tick", "t": t,
                    "actions": [ACTION_NAMES[int(a)] for a in actions],
                    "native": self.native,
                    "ops": [o.as_dict() for o in applied if o.kind != "noop-defer"],
                    "idle_agents": list(idle), "migrations": migrate_count,
                    "expired": sorted(expired), "sla_step": sla_step,
                    "completed": [n for n, _ in completed_now],
                    "refused_kubelet": [n for n, _ in refused_now],
                    "reward": reward.tolist(), "cost": cost.tolist(),
                    "in_system": in_system, "backlog": backlog_total,
                    "obs_report": {"stale": report.staleness_warning,
                                   "clamped": report.clamped,
                                   "over_one_util": report.refused_regime},
                    "snapshot_age_s": snap.max_info_age_s,   # API read span, NOT staleness (G-1)
                    "lag_s": lag, "gate": gate_log,
                    "t_obs_s": t_obs, "t_decided_s": t_dec, "t_ops_done_s": t_ops,
                    "planned_start_s": planned if live_clock else None,
                    "infra": infra_now or None,
                    "tick_wall_s": time.monotonic() - tick_t0, **adv}
            if self.log_obs:
                tick["obs"] = np.round(obs, 6).tolist()
            ticks.append(tick)
            self._emit(tick)

            # ---- admit the arrivals of step t ------------------------------ #
            self._admit(self.schedule.at(t), t)
            al = self._admit_lags(self.schedule.at(t))
            timing["admit_lag_s"].extend(al)
            done = [n for n, _ in completed_now]
            if done:
                be.gc(done)

        e1 = self.energy_probe.read() if self.energy_probe is not None else None
        te1 = time.monotonic()
        self._collect(final=True)                # after the energy interval closes
        cpu1, _ = be.cpu_seconds()
        qt = np.array(queue_trace) if queue_trace else np.array([0])
        task_recs, cohort = self._outcomes()
        self._emit({"type": "tasks", "records": task_recs})
        self._task_recs = task_recs
        wl_admitted = (workload_digest(self.admitted_originals)
                       if all(x.ordinal >= 0 for x in self.admitted_originals) else None)
        overruns = [tk.get("tick_overrun_s") for tk in ticks if tk.get("tick_overrun_s") is not None]
        summary = {
            "type": "summary", "backend": be.kind,
            "policy": getattr(self.policy, "name", type(self.policy).__name__),
            "info_class": policy_info_class(self.policy),
            "seed": self.schedule.seed, "horizon": self.horizon,
            "return_vec": ret.tolist(),                 # [-latency, -energy, -sla], P3 units
            "completed_tasks": ep["completed"],
            "mean_latency_steps": ep["latency_sum"] / max(1, ep["completed"]),
            "sla_violations": ep["sla_violations"],
            "total_energy_model": ep["energy_sum"],      # cloud_env FORMULA (MAPPING O-4)
            "mean_backlog": float(qt.mean()), "max_backlog": int(qt.max()),
            "mean_cost": (cost_sum / max(1, self.horizon)).tolist(),
            "c1_note": ("c1 is structurally 0 on Kubernetes (kubelet admission); "
                        "refused bindings are its observable counterpart (MAPPING G-9)"),
            "refused_bindings": tot["refused_sync"] + tot["refused_kubelet"],
            **tot,
            "cpu_seconds": (None if cpu0 is None or cpu1 is None else cpu1 - cpu0),
            "cpu_seconds_source": cpu_src,
            # protocol v1 7.1 primary endpoint, and 7.2 descriptive renames
            **cohort,
            "workload_digest_schedule": self.schedule.p3_digest,
            "workload_digest_admitted": wl_admitted,
            "workload_identity_ok": (wl_admitted is not None
                                     and wl_admitted == self.schedule.p3_digest),
            "gate_invariant_violations": self.gate_violations,
            "energy_proxy": (None if e0 is None else e1 - e0),
            "energy_interval_s": (None if e0 is None else te1 - te0),
            "energy_scope": (None if self.energy_probe is None else self.energy_probe.scope),
            "energy_max_read_gap_s": getattr(self.energy_probe, "max_gap_s", None),
            "energy_gap_ok": (None if self.energy_probe is None
                              else bool(getattr(self.energy_probe, "gap_ok", lambda: True)())),
            "timing": timing if live_clock else None,
            "infra_events": len(self.infra_events),
            "infra_event_kinds": sorted({e["kind"] for e in self.infra_events}),
            "infra_events_first": self.infra_events[:10],
            "gate_mismatches": len(self.gate_mismatches),
            "gate_mismatches_first": self.gate_mismatches[:10],
            "manifest_digest": self._manifest_digest(),
            "release_cap": self.release_cap if self.gated else None,
            "step_seconds": self.step_seconds, "deadline_eps_s": self.deadline_eps_s,
            "t0_unix": getattr(be, "t0_unix", None),
            "lag_s_max": max(lags) if lags else None,
            "lag_s_p99": float(np.percentile(lags, 99)) if lags else None,
            "tick_overrun_s_max": max(overruns) if overruns else None,
            "create_errors": getattr(be, "create_errors", 0),
            "container_execution_seconds_mean": (float(np.mean(completion_s)) if completion_s else None),
            # kept for backward compatibility: SAME value as above, misnamed
            "completion_seconds_mean": (float(np.mean(completion_s)) if completion_s else None),
            "completion_seconds_n": len(completion_s),
            "max_snapshot_age_s": max_age, "stale_ticks": stale_ticks,
            "clamped_ticks": clamp_ticks,
            "unfinished_at_end": len(led.active()),
            # per original task: outcome, censoring, pods (uid, node, evidence);
            # carried in the summary so analysis reads one file
            "task_records": task_recs,
            **self.meta,
        }
        self._emit(summary)
        return EpisodeResult(summary=summary, ticks=ticks)

    # -- reconciliation with what the cluster reports ----------------------- #
    def _reconcile(self, m: ClusterSnapshot, t: int, completion_s: list, tot: dict):
        """Classify every pod the ledger believes active against snapshot m."""
        seen = {p.name: p for p in m.pods}
        completed, refused = [], []
        for r in self.ledger.active():
            p = seen.get(r.name)
            if p is not None and not p.is_terminal:
                continue
            if p is not None and p.phase == "Failed" and not p.deleting:
                if (p.reason or "").startswith(REFUSAL_PREFIXES) and p.started_at is None:
                    refused.append((r.name, p.reason))
                    r.state, r.reason = "refused", p.reason
                    tot["refused_kubelet"] += 1
                else:
                    r.state, r.reason = "failed", p.reason
                    tot["failed_other"] += 1
                continue
            if r.state == "pending":
                # A pending pod cannot finish; vanishing means something else
                # deleted it. Recorded, never counted as a completion.
                r.state, r.reason = "failed", "vanished-while-pending"
                tot["failed_other"] += 1
                continue
            # Completion needs EVIDENCE (protocol v1 7.1): phase
            # Succeeded, or -- on the simulator backend only -- disappearance,
            # which is how cloud_env removes a finished task.
            if p is None and not getattr(self.backend, "completion_by_vanish", False):
                r.state, r.reason = "failed", "vanished-while-bound"
                tot["failed_other"] += 1
                continue
            if p is not None and p.phase != "Succeeded":
                r.state, r.reason = "failed", f"terminal-without-success:{p.phase}"
                tot["failed_other"] += 1
                continue
            r.state, r.completion_step = "completed", t
            if p is not None:
                r.started_at, r.finished_at = p.started_at, p.finished_at
                if p.started_at is not None and p.finished_at is not None:
                    completion_s.append(p.finished_at - p.started_at)
            completed.append((r.name, t - r.task.step))   # cloud_env.py:316
        return completed, refused

    def _requeue(self, refused: list, t: int, tot: dict) -> None:
        """A kubelet-rejected pod is Failed and cannot be re-bound. The task goes
        back into its agent's buffer as a NEW pod with its ORIGINAL arrival,
        deadline and FIFO position — the closest the cluster can come to the
        simulator, whose ACCEPT never fails (MAPPING.md A-1)."""
        tasks, names, agents = [], [], []
        for name, _reason in refused:
            old = self.ledger.recs[name]
            n_prev = sum(1 for r in self.ledger.recs.values()
                         if r.task.name == old.task.name) - 1
            new_name = f"{old.task.name}-r{n_prev + 1}"
            rec = self.ledger.admit(old.task, name=new_name, agent=old.agent,
                                    seq=old.enqueue_seq, requeued_from=name)
            rec.released = not self.gated
            tasks.append(old.task)
            names.append(new_name)
            agents.append(old.agent)
            tot["requeues"] += 1
        self.backend.gc([n for n, _ in refused])
        self.backend.admit(tasks, t, self.native, names, agents, gated=self.gated)

    # -- primary endpoint (protocol v1 7.1) --------------------------------- #
    def _outcomes(self) -> tuple[list[dict], dict]:
        """One outcome per ORIGINAL task, over all of its pods (requeues count
        toward the original). Cohort: deadline_step <= horizon - 1."""
        be = self.backend
        live = be.kind == "live"
        t0u = getattr(be, "t0_unix", None)
        admit_times = getattr(be, "admit_times", {}) or {}
        by_task: dict[str, list[PodRecord]] = {}
        for r in self.ledger.recs.values():
            by_task.setdefault(r.task.name, []).append(r)
        recs, counts, all_counts = [], dict.fromkeys(OUTCOMES, 0), dict.fromkeys(OUTCOMES, 0)
        resolved_done = resolved_exp = 0
        for task in self.admitted_originals:
            pods = by_task.get(task.name, [])
            out, info = adjudicate(task, pods, live=live, t0_unix=t0u,
                                   dt=self.step_seconds, eps=self.deadline_eps_s)
            in_cohort = task.deadline_step <= self.horizon - 1
            all_counts[out] += 1
            if in_cohort:
                counts[out] += 1
            resolved_done += any(r.state == "completed" for r in pods)
            resolved_exp += any(r.state == "expired" for r in pods)
            first = admit_times.get(task.name, (None, None))
            censored = out != "MET"
            recs.append({"task": task.name, "ordinal": task.ordinal, "step": task.step,
                         "deadline_step": task.deadline_step, "agent": task.agent,
                         "cohort": in_cohort, "outcome": out, "n_pods": len(pods),
                         "planned_admit_unix": first[0], "actual_admit_unix": first[1],
                         # response time is censored at the deadline when the task
                         # has no on-time success (protocol v1 7.2)
                         "censored": censored,
                         "censor_at": (None if not censored else
                                       ("deadline_wall" if live else "deadline_step")),
                         "pods": [{"name": r.name, "uid": r.uid, "state": r.state,
                                   "node_index": r.node_index, "bind_step": r.bind_step,
                                   "scheduled_at": r.scheduled_at,
                                   "requeued_from": r.requeued_from, "reason": r.reason,
                                   "evidence": r.evidence,
                                   "manifest": (getattr(be, "manifests", {}) or {}).get(r.name)}
                                  for r in pods],
                         **info})
        size = sum(counts.values())
        notmet = sum(counts[o] for o in NOT_MET)
        cohort = {
            "cohort_size": size,
            "cohort_counts": counts,
            "cohort_not_met_rate": (None if size == 0 else notmet / size),
            # bound with every EVIDENCE_LOST counted as met (reported, never used)
            "cohort_not_met_rate_if_lost_met": (None if size == 0 else
                                                (notmet - counts["EVIDENCE_LOST"]) / size),
            "evidence_lost": all_counts["EVIDENCE_LOST"],
            "all_arrivals_counts": all_counts,
            "conservation_ok": (sum(all_counts.values()) == len(self.admitted_originals)
                                == self.schedule.n_tasks),
            # the old fraction, renamed (protocol v1 7.1): descriptive only
            "miss_share_among_resolved": (None if resolved_done + resolved_exp == 0 else
                                          resolved_exp / (resolved_done + resolved_exp)),
        }
        return recs, cohort


def adjudicate(task: ScheduledTask, pods: list, *, live: bool, t0_unix: float | None,
               dt: float, eps: float) -> tuple[str, dict]:
    """Outcome of one original task over all of its pods (protocol v1 7.1).

    MET           some pod succeeded no later than the deadline: on dry-run
                  backends completion_step <= deadline_step; on the live cluster a
                  `Succeeded` termination with finishedAt <= t0 + d*dt + eps,
                  from the reconcile record OR the evidence read just before an
                  expiry deletion (completion/deletion race).
    MISSED        not MET, and the expiry rule fired or a pod succeeded late.
    EVIDENCE_LOST live only: not MET, and a pod deleted at expiry has no final
                  status (`evidence.lost`), so MET cannot be excluded.
    UNRESOLVED    a pod of the task is still pending or bound at the end.
    FAILED_OTHER  everything else: non-refusal failures, vanished pods, a success
                  without termination timestamps (no evidence, never assumed).
    """
    d = task.deadline_step
    met = late = False
    finish = start = None
    finish_step = None
    deadline_wall = (t0_unix + d * dt) if (live and t0_unix is not None) else None
    for r in pods:
        if live:
            ev = []
            if r.state == "completed" and r.finished_at is not None:
                ev.append((r.started_at, r.finished_at))
            e = r.evidence or {}
            if e.get("phase") == "Succeeded" and e.get("finished_at") is not None:
                ev.append((e.get("started_at"), e["finished_at"]))
            for st, fin in ev:
                if deadline_wall is not None and fin <= deadline_wall + eps:
                    met, start, finish = True, st, fin
                else:
                    late = True
                    finish = finish if finish is not None else fin
        elif r.state == "completed" and r.completion_step is not None:
            if r.completion_step <= d:
                met, finish_step = True, r.completion_step
            else:
                late = True
    if met:
        out = "MET"
    elif live and any(r.state == "expired" and (r.evidence or {}).get("lost") for r in pods):
        out = "EVIDENCE_LOST"
    elif late or any(r.state == "expired" for r in pods):
        out = "MISSED"
    elif any(r.state in ("pending", "bound") for r in pods):
        out = "UNRESOLVED"
    else:
        out = "FAILED_OTHER"
    info: dict = {"reasons": sorted({r.reason for r in pods if r.reason})}
    if live:
        arrival_wall = (t0_unix + task.step * dt) if t0_unix is not None else None
        info.update({"started_at": start, "finished_at": finish,
                     "deadline_wall": deadline_wall,
                     "response_s": (None if finish is None or arrival_wall is None
                                    else finish - arrival_wall)})
    else:
        info.update({"completion_step": finish_step,
                     "response_steps": (None if finish_step is None else finish_step - task.step)})
    return out, info


def _node_index(snap: ClusterSnapshot, node_name: str) -> int:
    for nd in snap.nodes:
        if nd.name == node_name:
            return nd.index
    raise KeyError(node_name)


def _json_default(o):
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, (np.floating,)):
        return float(o)
    if isinstance(o, np.ndarray):
        return o.tolist()
    return str(o)


def p3_code_fingerprint() -> dict:
    """sha256 of the P3 harness files the controller imports — provenance."""
    out = {}
    for f in ("cloud_env.py", "trace.py", "heuristics.py", "lyapunov.py"):
        p = P3_CODE / f
        if p.exists():
            out[f] = hashlib.sha256(p.read_bytes()).hexdigest()
    return out


