@dataclass
class PodRecord:
    name: str
    task: ScheduledTask
    agent: int                         # current routing (changes on MIGRATE)
    enqueue_seq: int                   # FIFO position (MAPPING O-9)
    state: str = "pending"             # pending|bound|completed|expired|refused|failed
    bind_order: int | None = None      # service order on the node (G-6)
    bind_step: int | None = None
    node_index: int | None = None
    completion_step: int | None = None
    started_at: float | None = None
    finished_at: float | None = None
    belief_remaining: float | None = None   # O-7: NOT observable on the cluster
    requeued_from: str | None = None
    reason: str | None = None
    #: arm A1: False while the pod still carries its scheduling gate
    released: bool = True
    #: terminal-state evidence of a pod deleted at expiry: first the read just
    #: before deletion (Op.evidence), then -- live -- the FINAL kubelet status
    #: collected from the retained object (`final: True`), or `lost`.
    evidence: dict | None = None
    #: live audit: metadata.uid, PodScheduled time (unix s), manifest digest
    uid: str | None = None
    scheduled_at: float | None = None
    manifest: str | None = None


class Ledger:
    def __init__(self) -> None:
        self.recs: dict[str, PodRecord] = {}
        self._seq = 0
        self._bind = 0

    def _next_seq(self) -> int:
        s = self._seq
        self._seq += 1
        return s

    def admit(self, task: ScheduledTask, name: str | None = None,
              agent: int | None = None, seq: int | None = None,
              requeued_from: str | None = None) -> PodRecord:
        name = name or task.name
        rec = PodRecord(name=name, task=task,
                        agent=task.agent if agent is None else agent,
                        enqueue_seq=self._next_seq() if seq is None else seq,
                        requeued_from=requeued_from)
        self.recs[name] = rec
        return rec

    def active(self) -> list[PodRecord]:
        return [r for r in self.recs.values() if r.state in ("pending", "bound")]

    def on_bind(self, name: str, node_index: int, step: int) -> None:
        r = self.recs[name]
        r.state, r.node_index, r.bind_step = "bound", node_index, step
        r.bind_order = self._bind
        self._bind += 1
        r.belief_remaining = r.task.work

    def on_retarget(self, name: str, agent: int) -> None:
        r = self.recs[name]
        r.agent = agent
        r.enqueue_seq = self._next_seq()     # cloud_env.py:208 appends to the TAIL

    def overlay(self, snap: ClusterSnapshot) -> ClusterSnapshot:
        """Impose ledger-held simulator state on a backend snapshot.

        * routing and FIFO order of pending pods come from the ledger, never
          from annotations (a live annotation can lag a retarget);
        * bound pods are ordered by bind order — the simulator's `running` list
          order, which defines its FIFO service head;
        * pods the ledger does not know (e.g. a previous run's) are dropped.
        """
        keep = []
        for p in snap.pods:
            r = self.recs.get(p.name)
            if r is None:
                continue
            p.enqueue_seq = r.enqueue_seq
            if p.node_index is None:
                p.initial_agent = r.agent
            elif r.state == "pending":
                # Bound by someone other than our executor — kube-scheduler in
                # the baseline run. Record it at first sight.
                self.on_bind(p.name, p.node_index, snap.step)
            keep.append(p)
        big = float("inf")
        keep.sort(key=lambda p: (self.recs[p.name].bind_order
                                 if self.recs[p.name].bind_order is not None else big,
                                 self.recs[p.name].enqueue_seq))
        snap.pods = keep
        return snap


